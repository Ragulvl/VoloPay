// ---- Main export function ----
export async function generateExport(
  records: StoredRecord[],
  generatedAt: string = new Date().toISOString()
): Promise<{ zip: Blob; manifest: ExportManifest }> {
  const zip = new JSZip();
  const manifestRecords: ManifestRecord[] = [];

  // Track all active output paths
  const allActivePaths: string[] = [];

  for (const record of records) {
    const activeRoutes = record.routes;
    const outputPaths: string[] = [];

    // Generate route documents
    for (const ra of activeRoutes) {
      const filePath = recordFilename(record, ra.route);
      const content = generateRouteDoc(record, ra.route);
      zip.file(filePath, content);
      outputPaths.push(filePath);
      allActivePaths.push(filePath);
    }

    // Generate context document
    const contextPath = contextFilename(record);
    const contextContent = generateContextDoc(record, outputPaths);
    zip.file(contextPath, contextContent);

    // Build manifest record
    const manifestRecord: ManifestRecord = {
      source_type: record.source_type,
      source_id: record.source_id,
      record_ref: record.record_ref,
      applied_revision: record.applied_revision,
      routes: activeRoutes.map((ra) => ({
        route: ra.route,
        source: ra.source,
      })),
      output_paths: outputPaths,
      superseded_paths: [],
      intake_state: record.intake_state,
      review_state: getReviewState(record),
      manual_override_flag: record.manual_override,
      analysis_freshness: (record.analysis?.freshness ?? 'current') as AnalysisFreshness,
    };
    manifestRecords.push(manifestRecord);
  }

  // Generate manager brief
  const briefContent = generateManagerBrief(records);
  zip.file('manager-brief.md', briefContent);

  // Build and add manifest
  const manifest: ExportManifest = {
    generated_at: generatedAt,
    total_records: records.length,
    records: manifestRecords,
  };
  zip.file('manifest.json', JSON.stringify(manifest, null, 2));

  // Add manifest verifier script
  const verifierScript = generateVerifierScript();
  zip.file('verify-manifest.js', verifierScript);

  // Generate ZIP blob
  const zipBlob = await zip.generateAsync({ type: 'blob' });

  return { zip: zipBlob, manifest };
}

function generateVerifierScript(): string {
  return `#!/usr/bin/env node
// verify-manifest.js
// Run: node verify-manifest.js
// Verifies every listed active output path exists in this export folder.

const fs = require('fs');
const path = require('path');

const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, 'manifest.json'), 'utf8'));
let errors = 0;
let checked = 0;

for (const record of manifest.records) {
  for (const outputPath of record.output_paths) {
    const fullPath = path.join(__dirname, outputPath);
    checked++;
    if (!fs.existsSync(fullPath)) {
      console.error('MISSING:', outputPath, '(record_ref:', record.record_ref + ')');
      errors++;
    }
  }
}

if (errors === 0) {
  console.log('All', checked, 'listed paths verified. Manifest is consistent.');
} else {
  console.error(errors, 'missing paths found out of', checked, 'checked.');
  process.exit(1);
}
`;
}

// ---- Download helper ----
export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
