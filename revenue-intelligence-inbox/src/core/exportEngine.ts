// ---- Slug helpers ----
function routeToSlug(route: Route): string {
  return route
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function id8(sourceId: string): string {
  return sourceId.replace(/-/g, '').substring(0, 8);
}

function recordFilename(record: StoredRecord, route: Route): string {
  const type = record.source_type;
  const id = id8(record.source_id);
  const ref = record.record_ref.toLowerCase();
  const routeSlug = routeToSlug(route);
  return `routes/${routeSlug}/${type}-${id}_${ref}.md`;
}

function contextFilename(record: StoredRecord): string {
  return `records/${record.source_type}/${record.source_id}/context.md`;
}

// ---- Review state helper ----
function getReviewState(record: StoredRecord): 'reviewed' | 'pending' | 'flagged' {
  if (!record.analysis) return 'pending';
  if (record.analysis.freshness === 'pending_review' || record.analysis.freshness === 'stale') {
    return 'flagged';
  }
  const hasFlags = (record.analysis.flags ?? []).length > 0;
  return hasFlags ? 'flagged' : 'reviewed';
}

// ---- Content generators ----
function generateRouteDoc(record: StoredRecord, route: Route): string {
  const analysis = record.analysis;
  const payload = record.payload;
  const refTime =
    record.source_type === 'call'
      ? (payload as CallPayload).started_at
      : (payload as MeetingPayload).starts_at;

  const lines: string[] = [
    `# ${route} — ${record.record_ref}`,
    '',
    `**Source:** ${record.source_type} / ${record.source_id}`,
    `**Record ref:** ${record.record_ref}`,
    `**Activity time (UTC):** ${refTime}`,
    `**Applied revision:** ${record.applied_revision}`,
    `**Intake state:** ${record.intake_state}`,
    `**Analysis freshness:** ${analysis?.freshness ?? 'n/a'}`,
    '',
    `## Route assignment`,
    '',
  ];

  const routeAssignments = record.routes.filter((r) => r.route === route);
  for (const ra of routeAssignments) {
    lines.push(`- **Source:** ${ra.source}`);
    lines.push(`- **Set at:** ${ra.setAt}`);
    if (ra.reason) lines.push(`- **Reason:** ${ra.reason}`);
  }

  if (analysis) {
    lines.push('');
    lines.push('## Analysis');
    lines.push('');
    lines.push(`**Confidence:** ${analysis.confidence}`);
    lines.push('');
    lines.push(`**Reason:** ${analysis.reason}`);

    if (analysis.quotes.length > 0) {
      lines.push('');
      lines.push('### Key quotes');
      for (const q of analysis.quotes) {
        lines.push(`> "${q}"`);
        lines.push('');
      }
    }

    if (analysis.evidenceTags.length > 0) {
      lines.push('### Evidence tags');
      for (const tag of analysis.evidenceTags) {
        const cite =
          tag.turnNumber
            ? `${tag.recordRef} turn ${tag.turnNumber}`
            : `${tag.recordRef}`;
        lines.push(`- **${tag.tag}** — ${cite}`);
        if (tag.quote) lines.push(`  > "${tag.quote}"`);
      }
    }

    if (analysis.unknowns.length > 0) {
      lines.push('');
      lines.push('### Unknowns');
      for (const u of analysis.unknowns) {
        lines.push(`- ${u}`);
      }
    }

    lines.push('');
    lines.push(`### Next action`);
    lines.push(analysis.nextAction);

    if (analysis.owner) {
      lines.push('');
      lines.push(`**Owner (source-stated):** ${analysis.owner}`);
    }

    if (analysis.flags && analysis.flags.length > 0) {
      lines.push('');
      lines.push('### Flags');
      for (const f of analysis.flags) {
        lines.push(`> ⚠️ ${f}`);
        lines.push('');
      }
    }
  }

  lines.push('');
  lines.push(`---`);
  lines.push(`*Generated by Revenue Intelligence Inbox. Analysis is pre-generated; app computes intake state, metrics and staleness.*`);

  return lines.join('\n');
}

function generateContextDoc(record: StoredRecord, outputPaths: string[]): string {
  const payload = record.payload;
  const refTime =
    record.source_type === 'call'
      ? (payload as CallPayload).started_at
      : (payload as MeetingPayload).starts_at;

  const lines: string[] = [
    `# Record context: ${record.record_ref}`,
    '',
    `**Source type:** ${record.source_type}`,
    `**Source ID:** ${record.source_id}`,
    `**Applied revision:** ${record.applied_revision}`,
    `**Activity time (UTC):** ${refTime}`,
    `**Intake state:** ${record.intake_state}`,
    `**Manual override:** ${record.manual_override}`,
    '',
    '## Routes',
    '',
  ];

  for (const ra of record.routes) {
    lines.push(`- **${ra.route}** (${ra.source})`);
  }

  lines.push('');
  lines.push('## Output files');
  lines.push('');
  for (const path of outputPaths) {
    lines.push(`- [${path}](../../${path})`);
  }

  if (record.change_history.length > 0) {
    lines.push('');
    lines.push('## Change history');
    lines.push('');
    for (const evt of record.change_history) {
      lines.push(`- **${evt.timestamp}** — ${evt.description}`);
    }
  }

  return lines.join('\n');
}

